"""Read/write the JSON files under backend/data: one file per patient and per category.

  patients/<id>.json           profile, history, followed axes, psychiatrist's recommendations (input)
  reports/<id>.json            consultation reports written by the psychiatrist (input)
  reports/generated/<id>.json  session summaries generated by the assistant
  conversations/<id>.json      every message of every conversation (conversation_id + timestamp)
  analyses/<id>.json           per-message scores and explanations
  mood_history/<id>.json       risk index and per-axis level/slope after each message
  alerts/<id>.json             alerts raised for the psychiatrist

Writes are atomic (temp file + replace) and serialised with a process-wide lock.
JSON files are fine for a single-server prototype, not for production.
"""
from __future__ import annotations

import json
import os
import re
import tempfile
import threading
import uuid
from datetime import datetime, timezone
from pathlib import Path

DATA = Path(os.environ.get("HACKPSY_DATA_DIR") or Path(__file__).resolve().parent.parent / "data")
GENERATED = ("conversations", "analyses", "mood_history", "alerts", "reports/generated")
_LOCK = threading.RLock()
_ID = re.compile(r"^[A-Za-z0-9_-]+$")


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def new_id() -> str:
    return uuid.uuid4().hex[:12]


def _path(category: str, pid: str) -> Path:
    if not _ID.match(pid):
        raise ValueError(f"invalid patient id: {pid!r}")
    return DATA / category / f"{pid}.json"


def _read(path: Path, default):
    with _LOCK:
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return default


def _write(path: Path, data) -> None:
    with _LOCK:
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent, suffix=".tmp")
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        os.replace(tmp, path)


def _append(category: str, pid: str, item: dict) -> dict:
    with _LOCK:
        p = _path(category, pid)
        items = _read(p, [])
        items.append(item)
        _write(p, items)
    return item


# --- patients -------------------------------------------------------------

def list_patients() -> list[dict]:
    out = []
    for p in sorted((DATA / "patients").glob("*.json")):
        d = _read(p, {})
        out.append({"patient_id": d.get("patient_id", p.stem), "alias": d.get("alias", p.stem),
                    "age": d.get("profile", {}).get("age")})
    return out


def get_patient(pid: str) -> dict | None:
    if not _ID.match(pid):
        return None
    return _read(_path("patients", pid), None)


def update_patient(pid: str, **fields) -> dict:
    with _LOCK:
        p = _path("patients", pid)
        patient = _read(p, None)
        if patient is None:
            raise KeyError(pid)
        patient.update(fields)
        _write(p, patient)
    return patient


def clear_history(pid: str) -> None:
    """Delete everything the app generated for this patient (inputs are kept)."""
    with _LOCK:
        for cat in GENERATED:
            _path(cat, pid).unlink(missing_ok=True)


# --- conversations / analyses / mood / alerts -----------------------------

def get_messages(pid: str, conversation_id: str | None = None) -> list[dict]:
    msgs = _read(_path("conversations", pid), [])
    return [m for m in msgs if m["conversation_id"] == conversation_id] if conversation_id else msgs


def add_message(pid: str, conversation_id: str, role: str, content: str, **extra) -> dict:
    return _append("conversations", pid, {"id": new_id(), "conversation_id": conversation_id, "ts": now(),
                                          "role": role, "content": content, **extra})


def get_analyses(pid: str) -> list[dict]:
    return _read(_path("analyses", pid), [])


def add_analysis(pid: str, entry: dict) -> dict:
    return _append("analyses", pid, entry)


def get_mood_history(pid: str) -> list[dict]:
    return _read(_path("mood_history", pid), [])


def add_mood_entry(pid: str, entry: dict) -> dict:
    return _append("mood_history", pid, entry)


def get_alerts(pid: str) -> list[dict]:
    return _read(_path("alerts", pid), [])


def add_alert(pid: str, alert: dict) -> dict:
    return _append("alerts", pid, {"id": new_id(), "ts": now(), **alert})


# --- reports --------------------------------------------------------------

def get_reports(pid: str) -> list[dict]:
    """Psychiatrist's consultation reports + generated session summaries, oldest first."""
    reports = _read(_path("reports", pid), []) + _read(_path("reports/generated", pid), [])
    return sorted(reports, key=lambda r: r.get("date", ""))


def add_report(pid: str, report: dict) -> dict:
    return _append("reports/generated", pid, {"report_id": new_id(), "date": now(), **report})
